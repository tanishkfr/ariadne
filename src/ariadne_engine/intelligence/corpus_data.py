"""Every family, split and source kind in the corpus, declared in one place.

A single table means adding a family cannot silently add a split nobody declared, and the
distribution a reader is shown comes from the same declaration the rows are built from.
"""


def cases() -> list[dict]:
    """Every reviewed case, in a stable order.

    Deterministic: families in the declared order, splits in the declared order, rows in
    authoring order. An evaluation that reorders its cases between runs has made two
    numbers incomparable, and the digest of the corpus would stop meaning anything.
    """
    built: list[dict] = []
    for family, tables in FAMILY_TABLES:
        for split, table, source_kind in tables:
            built.extend(_rows(family, split, source_kind, table))
    return built


def corpus() -> dict:
    """The assembled corpus document, ready to be evaluated."""
    return build(cases())


