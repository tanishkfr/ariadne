def _provenance(*, source_kind: str, second_reviewed: bool = False, adjudicated: str = "") -> dict:
    """The provenance block for one row, from the review round that produced it.

    ``source_kind`` is asserted against the declared vocabulary here rather than trusted from
    the row, so a typo in the data becomes a load error instead of a corpus that quietly
    claims a provenance it does not have.
    """
    if source_kind not in SOURCE_KINDS:
        raise ValueError(f"corpus row declares an unknown source kind: {source_kind!r}")
    record = dict(REVIEWERS["primary"])
    record["source_kind"] = source_kind
    if adjudicated:
        ruling = ADJUDICATIONS.get(adjudicated)
        if ruling is None:
            raise ValueError(f"corpus row claims adjudication {adjudicated!r} with no recorded ruling")
        record["agreement"] = "ADJUDICATED"
        record["second_reviewer"] = REVIEWERS["second"]["reviewer"]
        record["disagreement"] = ruling["disagreement"]
        record["adjudication"] = ruling["adjudication"]
        record["adjudicator"] = REVIEWERS["adjudicating"]["reviewer"]
    elif second_reviewed:
        record["agreement"] = "SECOND_REVIEWER_AGREED"
        record["second_reviewer"] = REVIEWERS["second"]["reviewer"]
    else:
        record["agreement"] = "SINGLE_REVIEWER"
    if record["agreement"] not in AGREEMENT_LEVELS:
        raise ValueError(f"corpus row declares an unknown agreement level: {record['agreement']!r}")
    return record


def _rows(
    family: str,
    split: str,
    source_kind: str,
    table: Sequence[tuple[str, str, Mapping[str, Any], str, bool]],
) -> list[dict]:
    """Turn one literal table into corpus rows.

    ``table`` rows are ``(case_id, label, projection, difficulty, expected_abstain)``. Nothing
    here derives a label: the label arrives already written and is checked against the family's
    declared answer space before it can be stored.
    """
    built: list[dict] = []
    for case_id, label, projection, difficulty, expected_abstain in table:
        built.append(
            case(
                case_id=case_id,
                family=family,
                split=split,
                projection=projection,
                label=label,
                provenance=_provenance(
                    source_kind=source_kind,
                    second_reviewed=case_id in SECOND_REVIEWED,
                    adjudicated=case_id if case_id in ADJUDICATIONS else "",
                ),
                expected_abstain=expected_abstain,
                difficulty=difficulty,
            )
        )
    return built


