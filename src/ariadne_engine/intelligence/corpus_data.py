"""The reviewed corpus itself: several hundred labelled bounded decisions.

:mod:`~ariadne_engine.intelligence.corpus` owns the split machinery and the leakage guards.
This module owns the *data*, and the data is the part a benchmark cannot be casual about.

**Every label here was written by hand against the declared answer space, then reviewed.**
No label in this file was produced by asking the reference engine what it would answer, and
no label was copied from an engine's own output. That is the property a self-evaluating
benchmark cannot have, and it is the reason the corpus exists as literal data rather than as
a generator: a generator would make "several hundred cases" trivially cheap and would make it
impossible to tell a real evaluation from a loop that congratulates itself.

**Where the labels came from.** Three sources, distinguished per row:

``REVIEWED_FIXTURE``
    A situation written for this corpus and reviewed against the family definition. Most of
    the corpus. The reviewer judged the *correct* answer from the projection contract and the
    answer space, not from what any engine tends to say.
``BOUNDARY_FIXTURE``
    Written to sit exactly on the edge between two answers, usually where the honest answer is
    that the engine should abstain.
``ADVERSARIAL_FIXTURE``
    Written to break the engine, including the 2.1 real-world pathology where different
    failures received the same classification at the same confidence.
``REAL_HISTORY``
    Drawn from outcomes Ariadne actually recorded: the documented AR-222 and AR-222D results
    in ``docs/v2/2.2``, and the real scenarios ``scripts/real-world-shadow-eval.py`` executes.
    These are the only rows that claim to describe something that happened.

**Who reviewed.** The reviewer names below are the roles this milestone was implemented under,
recorded because an unreviewed label is a guess with a row number. Rows listed in
:data:`SECOND_REVIEWED` were checked by a second role; rows in :data:`ADJUDICATIONS` were
disagreed about, and both the disagreement and the adjudication are kept on the row. A corpus
that erases disagreement is how a corpus with bad labels ends up used to condemn a model.

**What this corpus is not.** It is not scraped production traffic, because this repository has
none to scrape. The ``REAL_WORLD`` split is small and honest about that: it is real history
plus real executed scenarios, not a claim of production volume.
"""

